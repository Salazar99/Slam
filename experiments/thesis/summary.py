"""Assemble results/SUMMARY.md from the per-campaign outputs: python summary.py"""
import csv
import statistics as st
from collections import defaultdict

from common import RESULTS


def md(name):
    p = RESULTS / name
    return p.read_text().strip() if p.exists() else f"_{name} not produced yet_"


def rows(name):
    p = RESULTS / name
    return list(csv.DictReader(open(p))) if p.exists() else []


def sensitivity(name):
    """Range over the --min-final x th grid, per design."""
    by = defaultdict(list)
    for r in rows(name):
        by[r["case"]].append(r)
    out = ["| Design | N ass (min-max) | Coverage paper (min-max) | Cov. G≥0.9 (min-max) | Mean best-G (min-max) "
           "| Wall time s (min-max) |", "|---|---|---|---|---|---|"]
    for case, rs in by.items():
        rng = lambda k, f="{:.2f}": "–".join(f.format(v) for v in (min(float(r[k]) for r in rs), max(float(r[k]) for r in rs)))  # noqa: E731
        out.append(f"| {case} | {rng('n_ass', '{:.0f}')} | {rng('cov_paper') if 'cov_paper' in rs[0] else 'n/a'} "
                   f"| {rng('cov@0.9')} | {rng('meanG')} | {rng('wall_s')} |")
    return "\n".join(out)


def scalability():
    by = defaultdict(list)
    for r in rows("s2_scalability.csv"):
        if r["status"] == "ok":
            by[int(r["k"])].append(r)
    out = ["| dt numeric expressions | N ass | Mining time s (mean ± std, 5 runs) |", "|---|---|---|"]
    for k, rs in sorted(by.items()):
        w = [float(r["wall_s"]) for r in rs]
        out.append(f"| {k} | {rs[0]['n_ass']} | {st.mean(w):.3g} ± {st.stdev(w) if len(w) > 1 else 0:.2g} |")
    return "\n".join(out)


def main():
    text = f"""# Thesis experiment campaign: results

Generated by `summary.py` from `results/`. Environment: see `ENV.md`. Threats to validity: `threats.md`.
Ground truth: `../ground_truth.csv` (FDL 2024 designs + Simulink application examples).

## Table I (FDL designs)
The thesis reports the published FDL 2024 Table I for WaterTanks, Gearbox and Thermostat (time, N ass, N specs,
100% coverage, faulty water tanks). The rows below are the campaign's re-mining with the frozen binary, as a check.

## S1 + S6: requirement coverage (paper notion) and closeness to the golden reference (G)
*Coverage (paper)*: the requirement's own context yields at least one assertion that holds on all traces and is
triggered (the paper's "covered by at least one related assertion"). The G columns are stricter: best-G of each
requirement against the design's whole candidate set, i.e. closeness to an exact formalization.
Simulink golden reference: only requirements in SLAM's template (`ground_truth.csv`; the earlier set is in
`ground_truth_v1_simulink.csv`); its SLAM contexts are configured per requirement by `s2_sweep.py tune`
(grid in `s2_tuning.csv`), the FDL designs keep the paper's configs. LLM rows (S6) are mean ± std
over 5 samples.
`-req`: one formula per requirement text; `-trace`: assertions from a trace excerpt and SLAM's hints;
`-trace-checked`: only the trace-mode assertions that hold on the trace.

{md('s1_table.md')}

Per-requirement detail (best candidate, one-way scores): `s1_per_req.csv`.

LLM answers in and out of the G fragment, and how many fail on the traces (`-checked` drops them):

{md('s6_parse.md')}

## S2: sensitivity (ranking threshold --min-final × elbow th scale)
{sensitivity('s2_sensitivity.csv')}
{sensitivity('s2_sensitivity_sim.csv').split(chr(10), 2)[2] if rows('s2_sensitivity_sim.csv') else ''}

Full grids: `s2_sensitivity.md`, `s2_sensitivity_sim.md`.

## S2: scalability (WaterTanks, 1000-sample trace, 16 threads)
{scalability()}

Figure: `s2_scalability.pdf`.

## S2: fault detection
{md('faults.md')}

## Table I details (P/NE sets, templates, trace length)
{md('s2_tableI.md')}
"""
    (RESULTS / "SUMMARY.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
